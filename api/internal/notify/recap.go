/* The host's AI recap email: "Your AI recap: <topic>", once, right after a session ends.
 *
 * To the host only. It carries what the Results tab's recap card does — summary, key
 * points, action items, top questions — plus the attendance numbers, and links to the
 * Results tab and the recording when there is one. Same layout and palette as the
 * welcome and panelist emails. Everything in it but the numbers is model output or user
 * text, so it goes through html/template and is escaped by construction.
 */

// RecapNotice carries everything the recap email needs. Assembled by the caller.
type RecapNotice struct {
	Product      string
	HostName     string
	Topic        string
	Meeting      bool
	Recap        types.SessionRecap
	ResultsURL   string // absolute: the Results tab
	RecordingURL string // absolute: the host's recording, empty when there is none
}

type recapStat struct{ Label, Value string }

type recapView struct {
	RecapNotice
	Subject     string
	Preheader   string
	Greeting    string
	Lead        string
	Initial     string
	Stats       []recapStat
	ActionItems []string
	Questions   []string
	MSO         template.HTML
}

func recapStats(a types.RecapAttendance, meeting bool) []recapStat {
	var out []recapStat
	if !meeting && a.Registered > 0 {
		out = append(out, recapStat{"Registered", strconv.Itoa(a.Registered)})
	}
	out = append(out, recapStat{"Attended", strconv.Itoa(a.Attended)})
	if a.Peak > 0 {
		out = append(out, recapStat{"Peak at once", strconv.Itoa(a.Peak)})
	}
	if a.AvgWatchMin > 0 {
		out = append(out, recapStat{"Avg. watch", strconv.Itoa(a.AvgWatchMin) + " min"})
	}
	return out
}

// RecapEmail renders the host's recap email.
func RecapEmail(n RecapNotice) (subject, text, html string) {
	product := productName(n.Product)
	topic := oneLine(n.Topic)
	subject = "✨ Your AI recap: " + topic
	kind := "webinar"
	if n.Meeting {
		kind = "meeting"
	}
	v := recapView{
		RecapNotice: n,
		Subject:     subject,
		Preheader:   firstSentence(n.Recap.Summary),
		Greeting:    panelistGreeting(n.HostName),
		Lead:        "Here's the AI recap of your " + kind + " \"" + topic + "\", written from the session as soon as it ended.",
		Initial:     string([]rune(product)[0]),
		Stats:       recapStats(n.Recap.Attendance, n.Meeting),
		MSO:         msoFonts,
	}
	v.Product = product
	for _, a := range n.Recap.ActionItems {
		line := a.Text
		if a.Owner == types.RecapOwnerHost {
			line = "You: " + line
		}
		v.ActionItems = append(v.ActionItems, line)
	}
	for _, q := range n.Recap.TopQuestions {
		line := q.Question
		if q.Answered {
			line += " (answered)"
		} else {
			line += " (not answered yet)"
		}
		v.Questions = append(v.Questions, line)
	}

	var b strings.Builder
	b.WriteString(v.Greeting + "\n\n" + v.Lead + "\n\n")
	b.WriteString("Summary\n" + n.Recap.Summary + "\n\n")
	if len(v.Stats) > 0 {
		parts := make([]string, 0, len(v.Stats))
		for _, s := range v.Stats {
			parts = append(parts, s.Label+": "+s.Value)
		}
		b.WriteString("Attendance\n" + strings.Join(parts, " · ") + "\n\n")
	}
	list := func(title string, items []string) {
		if len(items) == 0 {
			return
		}
		b.WriteString(title + "\n")
		for _, it := range items {
			b.WriteString("- " + it + "\n")
		}
		b.WriteString("\n")
	}
	list("Key points", n.Recap.KeyPoints)
	list("Action items", v.ActionItems)
	list("Top questions", v.Questions)
	if n.Recap.Notice != "" {
		b.WriteString(n.Recap.Notice + "\n\n")
	}
	fmt.Fprintf(&b, "See the full results:\n%s\n\n", n.ResultsURL)
	if n.RecordingURL != "" {
		fmt.Fprintf(&b, "Watch the recording:\n%s\n\n", n.RecordingURL)
	}
	b.WriteString("This recap was generated by AI and may contain mistakes. Only you, the host, get this email.\n\n")
	b.WriteString("Thanks,\nThe " + product + " team\n")

	var hb bytes.Buffer
	if err := recapHTML.Execute(&hb, v); err != nil {
		return subject, b.String(), ""
	}
	return subject, b.String(), hb.String()
}

func firstSentence(s string) string {
	s = oneLine(s)
	if i := strings.Index(s, ". "); i > 0 {
		return s[:i+1]
	}
	return clip(s, 160)
}

