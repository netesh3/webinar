package notify

import (
	"strings"
	"testing"

	"github.com/netkumar/webcast/api/types"
)

func TestRecapEmail(t *testing.T) {
	n := RecapNotice{
		Product: "Webinar Liv", HostName: "Priya Sharma", Topic: "Money <basics>",
		Recap: types.SessionRecap{
			Summary:      "We covered budgets. People loved it.",
			KeyPoints:    []string{"Split in three"},
			ActionItems:  []types.RecapActionItem{{Text: "Share the sheet", Owner: types.RecapOwnerHost}, {Text: "Try it", Owner: types.RecapOwnerAttendee}},
			TopQuestions: []types.RecapQuestion{{Question: "Which SIP?", Answered: false}},
			Attendance:   types.RecapAttendance{Registered: 120, Attended: 64, Peak: 51, AvgWatchMin: 38},
		},
		ResultsURL:   "https://app.test/host/money?tab=results",
		RecordingURL: "https://app.test/host/money?tab=recording",
	}
	subject, text, html := RecapEmail(n)
	if subject != "Your AI recap: Money <basics>" {
		t.Errorf("subject = %q", subject)
	}
	for _, want := range []string{
		"Hi Priya,", "We covered budgets.", "Registered: 120 · Attended: 64 · Peak at once: 51 · Avg. watch: 38 min",
		"- You: Share the sheet", "- Try it", "- Which SIP? (not answered yet)",
		"https://app.test/host/money?tab=results", "Watch the recording:", "generated by AI",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("text is missing %q:\n%s", want, text)
		}
	}
	if !strings.Contains(html, "Money &lt;basics&gt;") || strings.Contains(html, "Money <basics>") {
		t.Error("the topic is not escaped in the HTML")
	}
	if !strings.Contains(html, "watch the recording") || !strings.Contains(html, "Peak at once") {
		t.Error("html is missing the recording link or the numbers")
	}

	// A meeting has no registrations to count, and no recording link without one.
	n.Meeting, n.RecordingURL = true, ""
	n.Recap.Notice = "Turn on captions next time for a full AI recap."
	_, text, _ = RecapEmail(n)
	if strings.Contains(text, "Registered") || strings.Contains(text, "Watch the recording") || !strings.Contains(text, "Turn on captions") {
		t.Errorf("meeting text = %s", text)
	}
}
