"use client";

import { useEffect, useRef, useState } from "react";
import { Spinner } from "./controls";
import { CopyIcon } from "./icons";
import { useToast } from "./providers";
import { Badge, Button, Card, SectionTitle } from "./ui";
import { ApiError, api } from "@/lib/api";
import type { SessionRecapResponse } from "@/lib/api-types";
import { useDevAuthBypassActive } from "@/lib/dev-bypass-session";
import {
  actionItemsText,
  formatChapterTime,
  recapEmptyState,
  recapSourceLabel,
} from "@/lib/recap";

/** How often a recap still being written is looked at again. */
const PENDING_POLL_MS = 30_000;

function regenerateError(err: unknown): string {
  if (!(err instanceof ApiError)) return "Couldn't reach the server. Try again in a minute.";
  switch (err.code) {
    case "ai_limit":
      return "AI limit reached for this month.";
    case "feature_off":
      return "AI is switched off for this account.";
    case "rate_limited":
      return "That's a few recaps in a row. Try again in a few minutes.";
  }
  return err.message || "The recap couldn't be written just now. Try again in a minute.";
}

/* The Results tab's AI recap card, for an ended session: what was covered, what the host
 * promised, what the audience asked. Written automatically when the session ends (and
 * emailed to the host); Regenerate writes it again. The empty states are lib/recap.ts. */
export function AIRecapCard({ slug }: { slug: string }) {
  const bypass = useDevAuthBypassActive();
  const { notify } = useToast();
  const [data, setData] = useState<SessionRecapResponse | null>(null);
  const [loadError, setLoadError] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [poll, setPoll] = useState(0);
  const inFlight = useRef(false);

  useEffect(() => {
    if (bypass) return;
    const ctl = new AbortController();
    let timer: ReturnType<typeof setTimeout> | undefined;
    async function load() {
      try {
        const res = await api.sessionRecap(slug, ctl.signal);
        if (ctl.signal.aborted) return;
        setData(res);
        setLoadError(false);
        if (res.status === "pending") timer = setTimeout(() => setPoll((n) => n + 1), PENDING_POLL_MS);
      } catch {
        if (!ctl.signal.aborted) setLoadError(true);
      }
    }
    void load();
    return () => {
      ctl.abort();
      if (timer) clearTimeout(timer);
    };
  }, [slug, bypass, poll]);

  if (bypass) return null;

  const regenerate = async () => {
    if (inFlight.current) return;
    inFlight.current = true;
    setBusy(true);
    setError(null);
    try {
      setData(await api.regenerateRecap(slug));
      notify("AI recap rewritten.", "ok");
    } catch (err) {
      setError(regenerateError(err));
    } finally {
      inFlight.current = false;
      setBusy(false);
    }
  };

  const copy = async (text: string, what: string) => {
    try {
      await navigator.clipboard.writeText(text);
      notify(`${what} copied.`, "ok");
    } catch {
      notify("Couldn't reach the clipboard.", "info");
    }
  };

  const header = (canGenerate: boolean, label: string) => (
    <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
      <div className="flex items-center gap-2">
        <SectionTitle>AI recap</SectionTitle>
        <span className="-mt-3">
          <Badge tone="brand">Generated by AI</Badge>
        </span>
      </div>
      {canGenerate && (
        <Button type="button" variant="secondary" size="sm" onClick={() => void regenerate()} disabled={busy}>
          {busy ? <Spinner /> : null}
          {busy ? "Writing…" : label}
        </Button>
      )}
    </div>
  );

  if (!data) {
    return (
      <Card className="p-5">
        {header(false, "")}
        <p className="text-[13px] text-ink-2">
          {loadError ? "Couldn't load the AI recap. Reload the page to try again." : "Loading the AI recap…"}
        </p>
      </Card>
    );
  }

  const empty = recapEmptyState(data);
  if (empty || !data.recap) {
    const state = empty ?? recapEmptyState({ status: "none" })!;
    return (
      <Card className="p-5">
        {header(state.canGenerate, data.status === "none" ? "Generate" : "Regenerate")}
        <p className="text-[13.5px] font-medium text-ink">
          {state.pending && <Spinner />} {state.title}
        </p>
        <p className="mt-1 text-[13px] text-ink-2">{state.detail}</p>
        {error && <p className="mt-2 text-[12.5px] text-live">{error}</p>}
      </Card>
    );
  }

  const r = data.recap;
  return (
    <Card className="p-5">
      {header(true, "Regenerate")}
      {error && <p className="mb-2 text-[12.5px] text-live">{error}</p>}
      <p className="text-[14px] leading-6 whitespace-pre-line text-ink">{r.summary}</p>

      {r.keyPoints.length > 0 && (
        <section className="mt-4">
          <h3 className="mb-1.5 text-[12px] font-semibold tracking-wide text-ink-3 uppercase">Key points</h3>
          <ul className="grid gap-1 pl-4 text-[13.5px] text-ink-2 [list-style:disc]">
            {r.keyPoints.map((k, i) => (
              <li key={i}>{k}</li>
            ))}
          </ul>
        </section>
      )}

      {r.actionItems.length > 0 && (
        <section className="mt-4">
          <div className="mb-1.5 flex items-center justify-between gap-2">
            <h3 className="text-[12px] font-semibold tracking-wide text-ink-3 uppercase">Action items</h3>
            <button
              type="button"
              onClick={() => void copy(actionItemsText(r.actionItems), "Action items")}
              className="inline-flex items-center gap-1 text-[12.5px] font-medium text-brand hover:underline"
            >
              <CopyIcon className="size-3.5" />
              Copy
            </button>
          </div>
          <ul className="grid gap-1.5 text-[13.5px] text-ink-2">
            {r.actionItems.map((a, i) => (
              <li key={i} className="flex items-start gap-2">
                <span aria-hidden className="mt-0.5 text-ink-3">☐</span>
                <span className="min-w-0 flex-1">{a.text}</span>
                {a.owner === "host" && <Badge tone="brand">You</Badge>}
                {a.owner === "attendee" && <Badge>Attendees</Badge>}
              </li>
            ))}
          </ul>
        </section>
      )}

      {r.chapters.length > 0 && (
        <section className="mt-4">
          <h3 className="mb-1.5 text-[12px] font-semibold tracking-wide text-ink-3 uppercase">Chapters</h3>
          <ol className="grid gap-1 text-[13.5px] text-ink-2">
            {r.chapters.map((c, i) => (
              <li key={i} className="flex gap-3">
                <span className="w-14 shrink-0 font-mono text-[12.5px] text-ink-3">{formatChapterTime(c.startSec)}</span>
                <span>{c.title}</span>
              </li>
            ))}
          </ol>
          <p className="mt-1 text-[12px] text-ink-3">Times are from when the session went live. The recording player shows them too.</p>
        </section>
      )}

      {r.topQuestions.length > 0 && (
        <section className="mt-4">
          <h3 className="mb-1.5 text-[12px] font-semibold tracking-wide text-ink-3 uppercase">Top questions</h3>
          <ul className="grid gap-1.5 text-[13.5px] text-ink-2">
            {r.topQuestions.map((q, i) => (
              <li key={i} className="flex items-start gap-2">
                <span className="min-w-0 flex-1">{q.question}</span>
                {q.upvotes > 0 && <span className="text-[12px] text-ink-3">▲ {q.upvotes}</span>}
                <Badge tone={q.answered ? "ok" : "warn"}>{q.answered ? "Answered" : "Not answered"}</Badge>
              </li>
            ))}
          </ul>
        </section>
      )}

      {r.notableQuotes.length > 0 && (
        <section className="mt-4">
          <h3 className="mb-1.5 text-[12px] font-semibold tracking-wide text-ink-3 uppercase">Notable quotes</h3>
          <div className="grid gap-2">
            {r.notableQuotes.map((q, i) => (
              <blockquote key={i} className="border-l-2 border-brand-line pl-3 text-[13.5px] text-ink-2 italic">
                “{q.text}”{q.speaker && <span className="not-italic text-ink-3"> — {q.speaker}</span>}
              </blockquote>
            ))}
          </div>
        </section>
      )}

      {r.notice && <p className="mt-4 rounded-lg bg-surface-2 px-3 py-2 text-[12.5px] text-ink-2">{r.notice}</p>}

      <p className="mt-4 text-[12px] text-ink-3">
        Generated by AI, so it may contain mistakes — check before you share it. {recapSourceLabel(data.source)}
        {data.emailedAt ? " We emailed you a copy." : ""}
      </p>
    </Card>
  );
}
